def safe_dict(val: Any) -> Dict[str, Any]:
    """Safely converts any input (JSON string, None, primitive) into a valid dictionary."""
    if isinstance(val, dict):
        return val
    if isinstance(val, str):
        try:
            parsed = json.loads(val)
            if isinstance(parsed, dict):
                return parsed
        except Exception:
            pass
    return {}

